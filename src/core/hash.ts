/**
 * Hashing primitives (integer-only, identical on every JS engine).
 *  - murmur3_32: fast non-cryptographic hash used ONLY for seed derivation by domain.
 *  - sha256: synchronous FIPS 180-4 implementation used for commitments and state hashes.
 */

export function murmur3(key: string, seed = 0): number {
  let h = seed >>> 0;
  const n = key.length;
  for (let i = 0; i < n; i++) {
    let k = key.charCodeAt(i);
    k = Math.imul(k, 0xcc9e2d51);
    k = (k << 15) | (k >>> 17);
    k = Math.imul(k, 0x1b873593);
    h ^= k;
    h = (h << 13) | (h >>> 19);
    h = (Math.imul(h, 5) + 0xe6546b64) | 0;
  }
  h ^= n * 2;
  return fmix32(h);
}

export function fmix32(h: number): number {
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  return h >>> 0;
}

/** Derive an independent uint32 from a uint32 seed and a domain label. */
export function deriveSeed(seed: number, label: string): number {
  return murmur3(label, seed >>> 0);
}

/** Stateless 2D integer hash -> uint32 (used by noise functions). */
export function hash2(x: number, y: number, seed: number): number {
  let h = (seed ^ Math.imul(x | 0, 0x27d4eb2d) ^ Math.imul(y | 0, 0x165667b1)) | 0;
  return fmix32(h);
}

